  fi
}

install_picsimlab() {
  if [[ "$INSTALL_PICSIMLAB" -ne 1 ]]; then
    return
  fi

  print_header "Installing PICSimLab"
  mkdir -p "$DOWNLOAD_DIR"
  log "installing PICSimLab from $PIC_SIMLAB_URL"

  if [[ "$(uname -m)" != "x86_64" ]]; then
    printf '%s\n' "${RED}PICSimLab pinned .deb is amd64 only; skipping on $(uname -m).${RESET}"
    FAILED_ITEMS+=("PICSimLab")
    log "PICSimLab skipped because architecture is not x86_64"
    return
  fi

  if [[ -r /etc/os-release ]]; then
    # shellcheck disable=SC1091
    . /etc/os-release
    if [[ "${ID:-}" != "ubuntu" ]]; then
      printf '%s\n' "${RED}PICSimLab install is configured for Ubuntu only; skipping.${RESET}"
      FAILED_ITEMS+=("PICSimLab")
      log "PICSimLab skipped because OS ID is ${ID:-unknown}"
      return
    fi

    if [[ "${VERSION_ID:-}" != "24.04" ]]; then
      printf '%s\n' "${YELLOW}This is Ubuntu ${VERSION_ID:-unknown}; the pinned PICSimLab package is built for Ubuntu 24.04.1.${RESET}"
      if ! prompt_yes_no "Continue with the pinned PICSimLab .deb anyway?" "n"; then
        SKIPPED_ITEMS+=("PICSimLab")
        log "PICSimLab skipped by user because Ubuntu version is ${VERSION_ID:-unknown}"
        return
      fi
    fi
  fi

  if ! curl -L --fail --output "$DOWNLOAD_DIR/$PIC_SIMLAB_DEB" "$PIC_SIMLAB_URL"; then
    FAILED_ITEMS+=("PICSimLab download")
    log "PICSimLab download failed"
    return
  fi

  if sudo dpkg -i "$DOWNLOAD_DIR/$PIC_SIMLAB_DEB"; then
    :
  else
    printf '%s\n' "${YELLOW}dpkg reported missing dependencies; running apt --fix-broken install.${RESET}"
    sudo apt --fix-broken install -y
  fi

  if picsimlab_installed; then
    INSTALLED_OTHER+=("PICSimLab")
    append_rollback "sudo apt purge -y picsimlab"
    append_rollback "sudo apt autoremove -y"
    log "PICSimLab installed"
  else
    FAILED_ITEMS+=("PICSimLab")
    log "PICSimLab install verification failed"
  fi
}

