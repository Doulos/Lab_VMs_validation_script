  fi
}

normalize_url() {
  case "$1" in
    http://*|https://*) printf '%s' "$1" ;;
    *) printf 'https://%s' "$1" ;;
  esac
}

url_host() {
  local url="$1"
  url="${url#http://}"
  url="${url#https://}"
  url="${url%%/*}"
  url="${url%%:*}"
  printf '%s' "$url"
}

url_port() {
  case "$1" in
    http://*) printf '%s' "80" ;;
    *) printf '%s' "443" ;;
  esac
}

test_tcp_reachable() {
  local url="$1"
  local host port

  host="$(url_host "$url")"
  port="$(url_port "$url")"

  if command_exists timeout; then
    timeout 5 bash -c ":</dev/tcp/$host/$port" >/dev/null 2>&1
  else
    bash -c ":</dev/tcp/$host/$port" >/dev/null 2>&1
  fi
}

test_site_reachable() {
  local input="$1"
  local url http_code

  url="$(normalize_url "$input")"

  if command_exists curl; then
    http_code="$(
      curl -L -sS -o /dev/null -w '%{http_code}' \
        --connect-timeout 5 \
        --max-time 12 \
        --compressed \
        -A 'Mozilla/5.0 embedded-rust-readiness-check' \
        "$url" 2>/dev/null || true
    )"
    if [[ "$http_code" != "000" && -n "$http_code" ]]; then
      return 0
    fi
  fi

  test_tcp_reachable "$url"
}

print_connectivity_summary() {
  local site url
  local reachable_count=0
  local failed_count=0

  print_header "Website reachability"
  printf '%-32s %-14s %s\n' "Site" "Result" "URL tested"
  printf '%-32s %-14s %s\n' "----" "------" "----------"

  for site in "${CONNECTIVITY_SITES[@]}"; do
    url="$(normalize_url "$site")"
    if test_site_reachable "$site"; then
      printf '%-32s %-23b %s\n' "$site" "$(status_label ok)" "$url"
      reachable_count=$((reachable_count + 1))
      log "site reachable: $url"
    else
      printf '%-32s %-23b %s\n' "$site" "$(status_label failed)" "$url"
      failed_count=$((failed_count + 1))
      log "site unreachable: $url"
    fi
  done

  printf '\nReachable: %s  Failed: %s\n' "$reachable_count" "$failed_count"
}

print_detection_table() {
  print_header "Readiness scan"
  printf '%-34s %-14s %s\n' "Item" "Status" "Verification"
  printf '%-34s %-14s %s\n' "----" "------" "------------"

  for package in "${APT_PACKAGES[@]}"; do
    if apt_installed "$package"; then
      printf '%-34s %-23b %s\n' "$package" "$(status_label present)" "dpkg"
    else
      printf '%-34s %-23b %s\n' "$package" "$(status_label missing)" "apt package"
    fi
  done

  if command_exists rustup; then
    printf '%-34s %-23b %s\n' "rustup" "$(status_label present)" "rustup --version"
  else
    printf '%-34s %-23b %s\n' "rustup" "$(status_label missing)" "$RUSTUP_INSTALLER_URL"
  fi

  for target in "${RUST_TARGETS[@]}"; do
    if rust_target_installed "$target"; then
      printf '%-34s %-23b %s\n' "rust target: $target" "$(status_label present)" "rustup target list"
    else
      printf '%-34s %-23b %s\n' "rust target: $target" "$(status_label missing)" "rustup target add"
    fi
  done

  if rust_component_installed llvm-tools; then
    printf '%-34s %-23b %s\n' "rust component: llvm-tools" "$(status_label present)" "rustup component list"
  else
    printf '%-34s %-23b %s\n' "rust component: llvm-tools" "$(status_label missing)" "rustup component add"
  fi

  for tool in "${CARGO_TOOLS[@]}"; do
    if cargo_tool_installed "$tool"; then
      printf '%-34s %-23b %s\n' "cargo tool: $tool" "$(status_label present)" "$(cargo_tool_check_label "$tool")"
    else
      printf '%-34s %-23b %s\n' "cargo tool: $tool" "$(status_label missing)" "cargo install"
    fi
  done

  if probe_rs_installed; then
    printf '%-34s %-23b %s\n' "probe-rs" "$(status_label present)" "probe-rs --version"
  else
    printf '%-34s %-23b %s\n' "probe-rs" "$(status_label missing)" "upstream installer"
  fi

  if picsimlab_installed; then
    printf '%-34s %-23b %s\n' "PICSimLab" "$(status_label present)" "package/command"
  else
    printf '%-34s %-23b %s\n' "PICSimLab" "$(status_label missing)" "$PIC_SIMLAB_DEB"
  fi
}

select_missing_items() {
  local package target tool

  print_header "Installation choices"
  printf '%s\n' "Answer yes for items you want this script to install now."

  for package in "${APT_PACKAGES[@]}"; do
    if ! apt_installed "$package"; then
      if prompt_yes_no "Install apt package '$package'?" "y"; then
        SELECTED_APT+=("$package")
      else
        SKIPPED_ITEMS+=("$package")
      fi
    fi
  done

  if ! command_exists rustup; then
    if prompt_yes_no "Install rustup using the official Rust installer?" "y"; then
      INSTALL_RUSTUP=1
    else
      SKIPPED_ITEMS+=("rustup")
    fi
  fi

  for target in "${RUST_TARGETS[@]}"; do
    if ! rust_target_installed "$target"; then
      if prompt_yes_no "Install Rust target '$target'?" "y"; then
        SELECTED_RUST_TARGETS+=("$target")
      else
        SKIPPED_ITEMS+=("rust target: $target")
      fi
    fi
  done

  if ! rust_component_installed llvm-tools; then
    if prompt_yes_no "Install Rust component 'llvm-tools'?" "y"; then
      INSTALL_LLVM_TOOLS=1
    else
      SKIPPED_ITEMS+=("rust component: llvm-tools")
    fi
  fi

  for tool in "${CARGO_TOOLS[@]}"; do
    if ! cargo_tool_installed "$tool"; then
      if prompt_yes_no "Install Cargo tool '$tool'?" "y"; then
        SELECTED_CARGO_TOOLS+=("$tool")
      else
        SKIPPED_ITEMS+=("cargo tool: $tool")
      fi
    fi
  done

  if ! probe_rs_installed; then
    if prompt_yes_no "Install probe-rs using the upstream installer?" "y"; then
      INSTALL_PROBE_RS=1
    else
      SKIPPED_ITEMS+=("probe-rs")
    fi
  fi

  if ! picsimlab_installed; then
    printf '%s\n' "${DIM}PICSimLab will use the pinned Ubuntu 24.04 asset: $PIC_SIMLAB_DEB${RESET}"
    if prompt_yes_no "Install PICSimLab from the pinned .deb?" "y"; then
      INSTALL_PICSIMLAB=1
    else
      SKIPPED_ITEMS+=("PICSimLab")
    fi
  fi
}

ensure_sudo() {
  if [[ "${#SELECTED_APT[@]}" -gt 0 || "$INSTALL_PICSIMLAB" -eq 1 ]]; then
    sudo -v
  fi
}

install_apt_packages() {
  local package

  if [[ "${#SELECTED_APT[@]}" -eq 0 ]]; then
    return
  fi

  print_header "Installing apt packages"
  log "apt selected: ${SELECTED_APT[*]}"

  if sudo apt update && sudo apt install -y "${SELECTED_APT[@]}"; then
    for package in "${SELECTED_APT[@]}"; do
      if apt_installed "$package"; then
        INSTALLED_APT+=("$package")
        append_rollback "sudo apt purge -y '$package'"
        log "apt installed: $package"
      else
        FAILED_ITEMS+=("$package")
        log "apt install verification failed: $package"
      fi
    done
    append_rollback "sudo apt autoremove -y"
    return
  fi

  printf '%s\n' "${YELLOW}Batch apt install failed; retrying packages individually.${RESET}"
  log "apt batch failed; retrying individually"

  for package in "${SELECTED_APT[@]}"; do
    if apt_installed "$package"; then
      continue
    fi

    if sudo apt install -y "$package" && apt_installed "$package"; then
      INSTALLED_APT+=("$package")
      append_rollback "sudo apt purge -y '$package'"
      log "apt installed after retry: $package"
    else
      FAILED_ITEMS+=("$package")
      log "apt install failed: $package"
    fi
  done
  append_rollback "sudo apt autoremove -y"
}

install_rustup_if_needed() {
  if [[ "$INSTALL_RUSTUP" -ne 1 ]]; then
    return
  fi

  print_header "Installing rustup"
  log "installing rustup"
  if curl --proto '=https' --tlsv1.2 -sSf "$RUSTUP_INSTALLER_URL" | sh -s -- -y; then
    source_cargo_env
    if command_exists rustup; then
      INSTALLED_OTHER+=("rustup")
      append_rollback "rustup self uninstall -y"
      log "rustup installed"
    else
      FAILED_ITEMS+=("rustup")
      log "rustup installer completed but rustup was not found"
    fi
  else
    FAILED_ITEMS+=("rustup")
    log "rustup installer failed"
  fi
}

install_rust_items() {
  local target tool

  source_cargo_env

  if [[ "${#SELECTED_RUST_TARGETS[@]}" -gt 0 || "$INSTALL_LLVM_TOOLS" -eq 1 ]]; then
    if ! command_exists rustup; then
      printf '%s\n' "${RED}rustup is unavailable; skipping Rust targets/components.${RESET}"
      for target in "${SELECTED_RUST_TARGETS[@]}"; do
        FAILED_ITEMS+=("rust target: $target")
      done
      [[ "$INSTALL_LLVM_TOOLS" -eq 1 ]] && FAILED_ITEMS+=("rust component: llvm-tools")
    fi
  fi

  if command_exists rustup; then
    for target in "${SELECTED_RUST_TARGETS[@]}"; do
      print_header "Installing Rust target $target"
      if rustup target add "$target" && rust_target_installed "$target"; then
        INSTALLED_RUST_TARGETS+=("$target")
        append_rollback "rustup target remove '$target'"
        log "rust target installed: $target"
      else
        FAILED_ITEMS+=("rust target: $target")
        log "rust target install failed: $target"
      fi
    done

    if [[ "$INSTALL_LLVM_TOOLS" -eq 1 ]]; then
      print_header "Installing Rust component llvm-tools"
      if rustup component add llvm-tools && rust_component_installed llvm-tools; then
        INSTALLED_OTHER+=("rust component: llvm-tools")
        append_rollback "rustup component remove llvm-tools"
        log "rust component installed: llvm-tools"
      else
        FAILED_ITEMS+=("rust component: llvm-tools")
        log "rust component install failed: llvm-tools"
      fi
    fi
  fi

  if [[ "${#SELECTED_CARGO_TOOLS[@]}" -gt 0 ]]; then
    if ! command_exists cargo; then
      printf '%s\n' "${RED}cargo is unavailable; skipping Cargo tools.${RESET}"
      for tool in "${SELECTED_CARGO_TOOLS[@]}"; do
        FAILED_ITEMS+=("cargo tool: $tool")
      done
      return
    fi

    for tool in "${SELECTED_CARGO_TOOLS[@]}"; do
      print_header "Installing Cargo tool $tool"
      if cargo install "$tool" && cargo_tool_installed "$tool"; then
        INSTALLED_CARGO_TOOLS+=("$tool")
        append_rollback "cargo uninstall '$tool'"
        log "cargo tool installed: $tool"
      else
        FAILED_ITEMS+=("cargo tool: $tool")
        log "cargo tool install failed: $tool"
      fi
    done
  fi
}

