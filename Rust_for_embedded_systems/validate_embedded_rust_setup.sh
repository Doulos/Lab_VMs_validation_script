print_header() {
  printf '\n%s%s%s\n' "$BOLD" "$1" "$RESET"
  printf '%*s\n' "${#1}" '' | tr ' ' '-'
}

log() {
  mkdir -p "$STATE_DIR" 2>/dev/null || true
  printf '[%s] %s\n' "$(date --iso-8601=seconds)" "$*" >> "$LOG_FILE"
}

prepare_runtime_dirs() {
  if ! mkdir -p "$STATE_DIR" 2>/dev/null || ! ( : > "$STATE_DIR/.write-test" ) 2>/dev/null; then
    printf '%s\n' "${YELLOW}Cannot write to $STATE_DIR; using a local log directory instead.${RESET}"
    STATE_DIR="$PWD/embedded-rust-setup-logs"
    mkdir -p "$STATE_DIR"
  else
    rm -f "$STATE_DIR/.write-test"
  fi

  if ! mkdir -p "$DOWNLOAD_DIR" 2>/dev/null || ! ( : > "$DOWNLOAD_DIR/.write-test" ) 2>/dev/null; then
    printf '%s\n' "${YELLOW}Cannot write to $DOWNLOAD_DIR; using a local download cache instead.${RESET}"
    DOWNLOAD_DIR="$PWD/embedded-rust-setup-downloads"
    mkdir -p "$DOWNLOAD_DIR"
  else
    rm -f "$DOWNLOAD_DIR/.write-test"
  fi

  LOG_FILE="$STATE_DIR/install-$RUN_ID.log"
  ROLLBACK_FILE="$STATE_DIR/rollback-$RUN_ID.sh"
}

init_rollback() {
  printf '[%s] run started\n' "$(date --iso-8601=seconds)" > "$LOG_FILE"

  {
    printf '#!/usr/bin/env bash\n'
    printf 'set -u\n'
    printf 'set -o pipefail\n\n'
    printf '# Rollback commands generated by validate_embedded_rust_setup.sh on %s.\n' "$(date --iso-8601=seconds)"
    printf '# Only items installed directly by that run are listed here.\n\n'
  } > "$ROLLBACK_FILE"
  chmod +x "$ROLLBACK_FILE"
}

append_rollback() {
  printf '%s\n' "$*" >> "$ROLLBACK_FILE"
}

status_label() {
  case "$1" in
    present) printf '%sinstalled%s' "$GREEN" "$RESET" ;;
    missing) printf '%smissing%s' "$RED" "$RESET" ;;
    selected) printf '%sselected%s' "$BLUE" "$RESET" ;;
    skipped) printf '%sskipped%s' "$YELLOW" "$RESET" ;;
    failed) printf '%sfailed%s' "$RED" "$RESET" ;;
    ok) printf '%sok%s' "$GREEN" "$RESET" ;;
    *) printf '%s' "$1" ;;
  esac
}

prompt_yes_no() {
  local prompt="$1"
  local default="${2:-n}"
  local answer suffix

  if [[ "$default" == "y" ]]; then
    suffix="[Y/n]"
  else
    suffix="[y/N]"
  fi

  while true; do
    printf '%s %s ' "$prompt" "$suffix"
    if ! read -r answer; then
      printf '\nNo input available; defaulting to no.\n'
      return 1
    fi
    answer="${answer:-$default}"
    case "$answer" in
      y|Y|yes|YES|Yes) return 0 ;;
      n|N|no|NO|No) return 1 ;;
      *) printf 'Please answer yes or no.\n' ;;
    esac
  done
}

command_exists() {
  command -v "$1" >/dev/null 2>&1
}

source_cargo_env() {
  if [[ -f "$HOME/.cargo/env" ]]; then
    # shellcheck disable=SC1091
    . "$HOME/.cargo/env"
  fi
}

apt_installed() {
  dpkg-query -W -f='${Status}' "$1" 2>/dev/null | grep -q 'install ok installed'
}

rust_target_installed() {
  command_exists rustup && rustup target list --installed 2>/dev/null | grep -Fxq "$1"
}

rust_component_installed() {
  command_exists rustup && rustup component list --installed 2>/dev/null | grep -Eq "^$1($|[ -])"
}

cargo_tool_installed() {
  case "$1" in
    cargo-binutils) command_exists cargo-size && cargo size --version >/dev/null 2>&1 ;;
    cargo-generate) command_exists cargo-generate || cargo generate --version >/dev/null 2>&1 ;;
    flip-link) command_exists flip-link ;;
    itm) command_exists itmdump && itmdump --version >/dev/null 2>&1 ;;
    *) return 1 ;;
  esac
}

cargo_tool_check_label() {
  case "$1" in
    cargo-binutils) printf '%s' "cargo size --version" ;;
    cargo-generate) printf '%s' "cargo-generate --version" ;;
    flip-link) printf '%s' "flip-link command" ;;
    itm) printf '%s' "itmdump --version" ;;
    *) printf '%s' "command/version" ;;
  esac
}

probe_rs_installed() {
  command_exists probe-rs && probe-rs --version >/dev/null 2>&1
}

picsimlab_installed() {
  apt_installed picsimlab || command_exists PICSimLab || command_exists picsimlab || command_exists PICSimLab_NOGUI
