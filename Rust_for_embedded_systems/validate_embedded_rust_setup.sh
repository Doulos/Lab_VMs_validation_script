}

verify_line() {
  local name="$1"
  local check="$2"
  local fn="$3"
  shift 3

  if "$fn" "$@"; then
    printf '%-34s %-23b %s\n' "$name" "$(status_label ok)" "$check"
  else
    printf '%-34s %-23b %s\n' "$name" "$(status_label failed)" "$check"
  fi
}

run_blinky_picsimlab_test() {
  local project_parent project_dir elf_file bin_file sim_cmd

  print_header "Rust and PICSimLab test"

  if ! prompt_yes_no "Create, build, and load a no_std Blue Pill blinky test in PICSimLab?" "n"; then
    log "Rust/PICSimLab integration test skipped by user"
    return
  fi

  source_cargo_env

  if ! command_exists cargo; then
    printf '%s\n' "${RED}cargo is not available; cannot build the test project.${RESET}"
    FAILED_ITEMS+=("Rust/PICSimLab test: cargo")
    log "Rust/PICSimLab test failed: cargo missing"
    return
  fi

  if ! rust_target_installed thumbv7m-none-eabi; then
    printf '%s\n' "${RED}Rust target thumbv7m-none-eabi is missing; cannot build for STM32F103.${RESET}"
    FAILED_ITEMS+=("Rust/PICSimLab test: thumbv7m-none-eabi")
    log "Rust/PICSimLab test failed: target missing"
    return
  fi

  if ! command_exists arm-none-eabi-objcopy; then
    printf '%s\n' "${RED}arm-none-eabi-objcopy is missing; install binutils-arm-none-eabi first.${RESET}"
    FAILED_ITEMS+=("Rust/PICSimLab test: objcopy")
    log "Rust/PICSimLab test failed: objcopy missing"
    return
  fi

  if ! sim_cmd="$(picsimlab_command)"; then
    printf '%s\n' "${RED}PICSimLab command was not found; cannot load the binary.${RESET}"
    FAILED_ITEMS+=("Rust/PICSimLab test: PICSimLab")
    log "Rust/PICSimLab test failed: PICSimLab command missing"
    return
  fi

  project_parent="${EMBEDDED_RUST_TEST_DIR:-$PWD/embedded-rust-setup-tests}"
  project_dir="$project_parent/blinky_app"
  mkdir -p "$project_dir/src" "$project_dir/.cargo"

  printf '%s\n' "${DIM}Writing test project to $project_dir${RESET}"

  cat > "$project_dir/Cargo.toml" <<'EOF'
[package]
name = "blinky_app"
version = "0.1.0"
edition = "2021"

[dependencies]
cortex-m = "0.7"
cortex-m-rt = "0.7"
panic-halt = "0.2"

[profile.release]
codegen-units = 1
debug = true
lto = true
opt-level = "s"
EOF

  cat > "$project_dir/.cargo/config.toml" <<'EOF'
[build]
target = "thumbv7m-none-eabi"

[target.thumbv7m-none-eabi]
rustflags = [
  "-C", "link-arg=-Tlink.x",
]
EOF

  cat > "$project_dir/build.rs" <<'EOF'
use std::env;

fn main() {
    println!(
        "cargo:rustc-link-search={}",
        env::var("CARGO_MANIFEST_DIR").unwrap()
    );
    println!("cargo:rerun-if-changed=memory.x");
}
EOF

  cat > "$project_dir/memory.x" <<'EOF'
MEMORY
{
  FLASH : ORIGIN = 0x08000000, LENGTH = 64K
  RAM : ORIGIN = 0x20000000, LENGTH = 20K
}
EOF

  cat > "$project_dir/src/main.rs" <<'EOF'
#![no_main]
#![no_std]

use core::ptr::{read_volatile, write_volatile};
use cortex_m_rt::entry;
use panic_halt as _;

const RCC_APB2ENR: *mut u32 = 0x4002_1018 as *mut u32;
const GPIOC_CRH: *mut u32 = 0x4001_1004 as *mut u32;
const GPIOC_BSRR: *mut u32 = 0x4001_1010 as *mut u32;
const GPIOC_BRR: *mut u32 = 0x4001_1014 as *mut u32;

#[entry]
fn main() -> ! {
    unsafe {
        let rcc = read_volatile(RCC_APB2ENR);
        write_volatile(RCC_APB2ENR, rcc | (1 << 4));

        let mut crh = read_volatile(GPIOC_CRH);
        crh &= !(0b1111 << 20);
        crh |= 0b0010 << 20;
        write_volatile(GPIOC_CRH, crh);
    }

    loop {
        unsafe {
            write_volatile(GPIOC_BRR, 1 << 13);
        }
        delay();

        unsafe {
            write_volatile(GPIOC_BSRR, 1 << 13);
        }
        delay();
    }
}

#[inline(never)]
fn delay() {
    for _ in 0..8_000_000 {
        cortex_m::asm::nop();
    }
}
EOF

  print_header "Building blinky_app"
  if ! (cd "$project_dir" && cargo build --release); then
    printf '%s\n' "${RED}cargo build --release failed for the test project.${RESET}"
    FAILED_ITEMS+=("Rust/PICSimLab test: cargo build")
    log "Rust/PICSimLab test failed: cargo build"
    return
  fi

  elf_file="$project_dir/target/thumbv7m-none-eabi/release/blinky_app"
  bin_file="$project_dir/blinky_app.bin"

  print_header "Creating blinky_app.bin"
  if ! arm-none-eabi-objcopy -O binary "$elf_file" "$bin_file"; then
    printf '%s\n' "${RED}arm-none-eabi-objcopy failed.${RESET}"
    FAILED_ITEMS+=("Rust/PICSimLab test: objcopy")
    log "Rust/PICSimLab test failed: objcopy"
    return
  fi

  print_header "Launching PICSimLab"
  printf '%s\n' "${DIM}Running: $sim_cmd Blue_Pill stm32f103c8t6 $bin_file${RESET}"
  log "Rust/PICSimLab test launching: $sim_cmd Blue_Pill stm32f103c8t6 $bin_file"

  if (cd "$project_dir" && "$sim_cmd" Blue_Pill stm32f103c8t6 blinky_app.bin); then
    INSTALLED_OTHER+=("Rust/PICSimLab blinky test")
    log "Rust/PICSimLab test completed"
  else
    FAILED_ITEMS+=("Rust/PICSimLab test: launch")
    log "Rust/PICSimLab test launch failed"
  fi
}

print_run_summary() {
  local item

  print_header "Run summary"
  printf '%-34s %-14s\n' "Item" "Outcome"
  printf '%-34s %-14s\n' "----" "-------"

  for item in "${INSTALLED_APT[@]}"; do
    printf '%-34s %-23b\n' "$item" "$(status_label ok)"
  done
  for item in "${INSTALLED_RUST_TARGETS[@]}"; do
    printf '%-34s %-23b\n' "rust target: $item" "$(status_label ok)"
  done
  for item in "${INSTALLED_CARGO_TOOLS[@]}"; do
    printf '%-34s %-23b\n' "cargo tool: $item" "$(status_label ok)"
  done
  for item in "${INSTALLED_OTHER[@]}"; do
    printf '%-34s %-23b\n' "$item" "$(status_label ok)"
  done
  for item in "${SKIPPED_ITEMS[@]}"; do
    printf '%-34s %-23b\n' "$item" "$(status_label skipped)"
  done
  for item in "${FAILED_ITEMS[@]}"; do
    printf '%-34s %-23b\n' "$item" "$(status_label failed)"
  done

  printf '\nLog:      %s\n' "$LOG_FILE"
  printf 'Rollback: %s\n' "$ROLLBACK_FILE"
}

check_ubuntu() {
  if [[ ! -r /etc/os-release ]]; then
    printf '%s\n' "${RED}Cannot read /etc/os-release; this script supports Ubuntu only.${RESET}"
    exit 1
  fi

  # shellcheck disable=SC1091
  . /etc/os-release
  if [[ "${ID:-}" != "ubuntu" ]]; then
    printf '%s\n' "${RED}Unsupported OS '${ID:-unknown}'. This script supports Ubuntu only.${RESET}"
    exit 1
  fi
}

